#!/usr/bin/env python3
"""Build the "Meet the crew" section.

Reads tools/crew/crew.json, cuts a square portrait for each friend from a photo in assets/img/
(crop = [left, top, side] as fractions of the photo's width/height/width), writes it to
assets/img/crew/<slug>.jpg, counts the gallery photos whose caption or alt text mentions the friend,
and rewrites everything between the CREW:GENERATED markers in index.html.

Run from anywhere:  python3 tools/crew/build_crew.py
"""
import html, json, os, re
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
IMG = os.path.join(ROOT, 'assets', 'img')

with open(os.path.join(HERE, 'crew.json'), encoding='utf-8') as f:
    crew = json.load(f)
index_path = os.path.join(ROOT, 'index.html')
with open(index_path, encoding='utf-8') as f:
    page = f.read()

photos = [html.unescape(m.group(1) + ' ' + m.group(2)) for m in
          re.finditer(r'<a class="photo[^>]*data-caption="([^"]*)">\s*<img src="[^"]*" alt="([^"]*)"', page)]

cards = ''
for member in crew:
    im = Image.open(os.path.join(IMG, member['photo'])).convert('RGB')
    w, h = im.size
    left, top, side = member['crop']
    box = (int(left * w), int(top * h), min(int((left + side) * w), w), min(int(top * h + side * w), h))
    out = os.path.join(IMG, 'crew', member['slug'] + '.jpg')
    im.crop(box).resize((320, 320), Image.LANCZOS).save(out, 'JPEG', quality=82, optimize=True)
    seen = sum(1 for text in photos if any(word in text for word in member['match']))
    cards += ('          <li class="crew-card">\n'
              '            <img src="assets/img/crew/%s.jpg" alt="%s" loading="lazy" width="320" height="320">\n'
              '            <h3 class="crew-name">%s</h3>\n'
              '            <p class="crew-bio">%s</p>\n'
              '            <p class="crew-count">In %d photo%s</p>\n'
              '          </li>\n' % (member['slug'], html.escape(member['name']), html.escape(member['name']),
                                     html.escape(member['bio']), seen, '' if seen == 1 else 's'))
    print('%-14s %2d photos  <- %s' % (member['name'], seen, member['photo']))

generated = ('        <!-- CREW:GENERATED by tools/crew/build_crew.py from tools/crew/crew.json. Edit that file, not this block. -->\n'
             '        <ul class="crew-grid reveal">\n%s        </ul>\n'
             '        <!-- /CREW:GENERATED -->' % cards)
page, n = re.subn(r'        <!-- CREW:GENERATED.*?<!-- /CREW:GENERATED -->', lambda m: generated, page, flags=re.S)
if n != 1:
    raise SystemExit('index.html needs exactly one CREW:GENERATED block')
with open(index_path, 'w', encoding='utf-8') as f:
    f.write(page)
